/** Smooth 8 m flyover with ~180 m approach ramps and a level crossing deck. */
export function kairoRoadLiftAt(progress: number): number {
  const ease = (value: number) => { const t = Math.max(0, Math.min(1, value)); return t * t * (3 - 2 * t); };
  return 8 * ease((progress - .807) / .031) * ease((.891 - progress) / .031);
}

